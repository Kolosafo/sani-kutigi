export function getSkill(slug: string): Skill | undefined {
  return skills.find((skill) => skill.slug === slug);
}

export function getSkills(track?: SkillTrack): Skill[] {
  return track ? skills.filter((skill) => skill.track === track) : skills;
}

export function getCategories(): string[] {
  return [...new Set(skills.map((skill) => skill.category))].sort();
}

export function trackLabel(track: SkillTrack): string {
  return track === "code" ? "Coding" : "No-code";
}

export function countResources(): number {
  return skills.reduce((total, skill) => total + skill.resources.length, 0);
}
